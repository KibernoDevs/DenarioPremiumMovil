 await D.goto(pg,PAGE); await pg.waitForTimeout(2500);
 console.log('cump='+await D.pick(pg,`${F}:cumplimiento`,CUMP));
 console.log('cur='+await D.pick(pg,`${F}:idCurrency`,CUR));
 await pg.evaluate(([f,x,y])=>{const a=document.getElementById(f+':dateB_input');if(a)a.value=x;const b=document.getElementById(f+':dateF_input');if(b)b.value=y;},[F,D1,D2]);
 const st=await pg.evaluate((f)=>({vend:document.getElementById(f+':vendedor_input')?.value,cump:document.getElementById(f+':cumplimiento_input')?.value,cur:document.getElementById(f+':idCurrency_input')?.value,d1:document.getElementById(f+':dateB_input')?.value,d2:document.getElementById(f+':dateF_input')?.value}),F);
