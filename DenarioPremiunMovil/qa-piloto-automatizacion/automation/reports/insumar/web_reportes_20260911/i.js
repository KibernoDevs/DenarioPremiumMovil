 console.log('---TXT---\n'+t.slice(i>=0?i:0,(i>=0?i:0)+2500));
 const tabs=await pg.evaluate(()=>[...document.querySelectorAll('table')].map(tb=>[...tb.querySelectorAll('tr')].map(tr=>[...tr.querySelectorAll('th,td')].map(c=>c.innerText.trim().replace(/\s+/g,' ')).join(' | ')).join('\n')).filter(x=>x.length>10));
